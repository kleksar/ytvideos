GRAIN_PRESETS = json.loads((HERE / "grain_presets.json").read_text())
IDENTITY_TRANSFORM = {"centerX": .5, "centerY": .5, "width": 1, "height": 1, "rotation": 0,
                      "flipHorizontal": False, "flipVertical": False}


def emit(**values):
    print(json.dumps(values, ensure_ascii=False), flush=True)


def save(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    temporary.replace(path)


def digest(data):
    return hashlib.sha256(json.dumps(data, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def file_hash(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def canonical(value):
    """Remove only identity fields regenerated by timeline cloning."""
    if isinstance(value, dict):
        return {k: canonical(v) for k, v in value.items()
                if k not in {"id", "trackId", "timelineId", "captionGroupId", "timelines", "canGenerate",
                             "maskOverlayVisible", "currentFrame", "visible"}}
    if isinstance(value, list):
        return [canonical(v) for v in value]
    return value


def fingerprint(timeline):
    result = canonical(timeline)
    result.pop("name", None)
    return digest(result)


def equal(a, b):
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return abs(a - b) <= 0.00101  # Palmier get_timeline rounds to three decimals.
    if isinstance(a, dict) and isinstance(b, dict):
        return a.keys() == b.keys() and all(equal(a[k], b[k]) for k in a)
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(equal(x, y) for x, y in zip(a, b))
    return a == b


def track(state, name):
    found = [t for t in state["tracks"] if t.get("name", t.get("label")) == name]
    if len(found) != 1:
        raise ValueError(f"Expected one scene track named {name!r}, found {len(found)}")
    return found[0]


class Palmier:
    def __init__(self, run_dir):
        spec = importlib.util.spec_from_file_location(
            "ytv_palmier", ROOT / "automation/palmier/inspect_connection.py")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        self.connection = module.PalmierConnection()
        self.connection.connect()
        self.run_dir = run_dir
        self.schemas = {t["name"]: t for t in self.connection.request("tools/list")["tools"]}

    def call(self, name, args, mutation=False):
        if name not in self.schemas:
            raise RuntimeError(f"Palmier no longer provides {name}; inspect tools/list")
        pending = self.run_dir / "pending.json"
        if mutation:
            if pending.exists():
                raise RuntimeError(f"Unreconciled operation: {pending}")
            save(pending, {"name": name, "arguments": args, "time": time.time()})
        response = self.connection.request("tools/call", {"name": name, "arguments": args})
        with (self.run_dir / "receipts.jsonl").open("a") as stream:
            stream.write(json.dumps({"name": name, "arguments": args, "response": response}) + "\n")
            stream.flush()
            os.fsync(stream.fileno())
        if response.get("isError"):
            raise RuntimeError(f"{name} failed; inspect receipts in {self.run_dir}")
        texts = [x["text"] for x in response.get("content", []) if x.get("type") == "text"]
        if len(texts) != 1:
            raise RuntimeError(f"Unexpected {name} response; reconcile before retry")
        result = json.loads(texts[0])
        if mutation:
            pending.unlink()
        return result


def path_from(value, base):
    p = Path(value).expanduser()
    return (p if p.is_absolute() else base / p).resolve()


def camera_keys(clip, factor, mode, number):
    n = clip["frames"][1] - clip["frames"][0]
    old = copy.deepcopy(clip.get("keyframes", {}))
    p, s = old.get("position"), old.get("scale")
    if mode == "existing":
        if not p and not s:
            return old, 0.0
        if not p or not s or len(p) < 2 or len(p) != len(s):
            raise ValueError("Preserving existing camera requires matching position and scale keyframes")
        if any(p[i][0] != s[i][0] for i in range(len(p))):
            raise ValueError("Existing position and scale camera keys must use matching frames")
        centers = [p[i][1] + s[i][1] / 2 for i in (0, -1)]
        return old, centers[1] - centers[0]
    if mode == "auto" and not p and not s:
        mode = ("pan-right", "push-in", "pan-left", "pan-up", "pull-out", "pan-down")[number % 6]
    if mode not in {"auto", "existing"}:
        transform = clip.get("transform", {})
        width, height = transform.get("width", 1), transform.get("height", 1)
        if abs(width - height) > .005:
            raise ValueError("Nonuniform source transform needs an explicit camera path")
        cx, cy = transform.get("centerX", .5), transform.get("centerY", .5)
        base = max(1.04, width, height)
        size0 = base if mode == "push-in" else base + .06
        size1 = base if mode == "pull-out" else base + .06
        delta = {"pan-right": (.06, 0), "pan-left": (-.06, 0),
                 "pan-up": (0, -.06), "pan-down": (0, .06),
                 "push-in": (0, 0), "pull-out": (0, 0)}[mode]
        s = [[0, size0, size0, "linear"], [n - 1, size1, size1]]
        p = [[0, cx-delta[0]/2-size0/2, cy-delta[1]/2-size0/2, "linear"],
             [n-1, cx+delta[0]/2-size1/2, cy+delta[1]/2-size1/2]]
        if any(row[a] > 1e-8 or row[a] + scale[a] < 1-1e-8
               for row, scale in zip(p, s) for a in (1, 2)):
            raise ValueError("Camera would expose canvas edges; use an explicit safe framing")
    elif not p and not s:
        return old, 0.0
    elif not p or not s:
        # Fill the missing constant property from the static transform.
        transform = clip.get("transform", {})
        width, height = transform.get("width", 1), transform.get("height", 1)
        if not s:
            s = [[row[0], width, height, *row[3:]] for row in p]
        if not p:
            x, y = transform.get("centerX", .5)-width/2, transform.get("centerY", .5)-height/2
            p = [[row[0], x, y, *row[3:]] for row in s]
    if len(p) != 2 or len(s) != 2 or [r[0] for r in p] != [r[0] for r in s]:
        raise ValueError("Camera reduction supports two matching endpoint keys; complex paths need an explicit camera override")
    if p[0][0] != 0 or p[-1][0] <= 0:
        raise ValueError("Camera keys must start at zero and have a later endpoint")
    centers = [[p[i][a]+s[i][a]/2 for a in (1, 2)] for i in (0, 1)]
    news = [[r[0], *[(s[0][a]+s[1][a])/2 + factor*(r[a]-(s[0][a]+s[1][a])/2)
                     for a in (1, 2)], *r[3:]] for r in s]
    newp = [[r[0], *[(centers[0][a-1]+centers[1][a-1])/2 +
                     factor*(centers[i][a-1]-(centers[0][a-1]+centers[1][a-1])/2)-news[i][a]/2
                     for a in (1, 2)], *r[3:]] for i, r in enumerate(p)]
    old.update(position=newp, scale=news)
    return old, factor*(centers[1][0]-centers[0][0])


def grain_settings(config):
    name = config.get("grain", GRAIN_PRESETS["default"])
    if name == "none":
        return None
    if name not in GRAIN_PRESETS["presets"]:
        raise ValueError(f"Unknown grain preset {name!r}; use g08 or none")
    return {"id": name, **GRAIN_PRESETS["presets"][name]}


def finish_plan(scene):
    """Fail before rendering/mutation when camera cannot be reproduced faithfully."""
    if scene["fps"] != scene["grain"]["update_hz"] or scene["width"] % 2 or scene["height"] % 2:
        raise ValueError("G08 supports 30fps and even canvas dimensions; use grain:none for other rates")
    original = scene["source"]
    if set(scene["keyframes"]) - {"position", "scale", "opacity"}:
        raise ValueError("G08 camera bake supports position/scale and opacity only")
    transform = original.get("transform", {})
    if (set(transform)-IDENTITY_TRANSFORM.keys() or transform.get("rotation", 0) != 0 or
            transform.get("flipHorizontal", False) or transform.get("flipVertical", False)):
        raise ValueError("G08 does not support rotated/flipped/custom transforms")
    if original.get("crop") and any(original["crop"].values()):
        raise ValueError("G08 needs uncropped full-frame sources; custom crop requires an explicit adapter")
    keys = {k: copy.deepcopy(v) for k, v in scene["keyframes"].items() if k in {"position", "scale"}}
    if not keys:
        sx, sy = transform.get("width", 1), transform.get("height", 1)
        x, y = transform.get("centerX", .5)-sx/2, transform.get("centerY", .5)-sy/2
        keys = {"position": [[0, x, y, "linear"], [scene["frames"]-1, x, y]],
                "scale": [[0, sx, sy, "linear"], [scene["frames"]-1, sx, sy]]}
    for name in ("position", "scale"):
        rows = keys[name]
        if (len(rows) != 2 or rows[0][0] != 0 or rows[1][0] <= 0 or
                len(rows[0]) > 4 or len(rows[1]) > 4 or
                (len(rows[0]) == 4 and rows[0][3] != "linear") or
                (len(rows[0]) < 4 and rows[0][1:3] != rows[1][1:3])):
            raise ValueError("G08 requires linear endpoint camera keys; set an explicit standard camera mode")
        if not all(isinstance(v, (int, float)) and math.isfinite(v) for row in rows for v in row[:3]):
            raise ValueError("Nonfinite camera values")
    if keys["position"][1][0] != keys["scale"][1][0]:
        raise ValueError("Camera endpoint times must match")
    # Linear affine bounds stay valid between endpoints; held tails use the endpoint.
    for p, s in zip(keys["position"], keys["scale"]):
        for axis in (1, 2):
            if s[axis] <= 0 or p[axis] > 1e-8 or p[axis]+s[axis] < 1-1e-8:
                raise ValueError("Camera exposes canvas edges; correct framing before G08 bake")
    scene["baked_camera"] = keys
    scene["target_keyframes"] = {k: v for k, v in scene["keyframes"].items() if k not in {"position", "scale"}}
    # Camera is already in the media; an identity transform prevents applying it twice.
    scene["target_transform"] = {"centerX": .5, "centerY": .5, "width": 1, "height": 1, "rotation": 0}


def make_plan(config, state, base, limit=None):
    preset = PRESETS[config.get("preset", "gentle-aligned")]
    scene_track = track(state, config.get("scene_track", "Scenes"))
    manifest_path = path_from(config["source_manifest"], base)
    manifest = json.loads(manifest_path.read_text())
    rows = manifest if isinstance(manifest, list) else manifest["scenes"]
    planned = []
    selected = sorted(scene_track["clips"], key=lambda x: x["frames"][0])
    if limit:
        selected = selected[:limit]
    for i, clip in enumerate(selected):
        if clip.get("mediaType") != "image":
            raise ValueError("Use the baseline still-image timeline, not an already rendered parallax branch")
        start, end = clip["frames"]
        matches = [r for r in rows if r.get("clipId") == clip["id"]]
        if not matches:
            matches = [r for r in rows if r.get("mediaRef") == clip["mediaRef"]]
        if len(matches) != 1:
            matches = [r for r in rows if r.get("startFrame", r.get("start_frame")) == start
                       and r.get("endFrame", r.get("end_frame")) == end]
        if len(matches) != 1:
            raise ValueError(f"Source manifest must uniquely match mediaRef, clipId or interval [{start},{end})")
        row = matches[0]
        if row.get("mediaRef") and row["mediaRef"] != clip["mediaRef"]:
            raise ValueError(f"Source mediaRef mismatch at {start}")
        image = path_from(row.get("framed_path", row.get("image", row.get("path", ""))), manifest_path.parent)
        if not image.is_file() or image.suffix.lower() not in {".png", ".jpg", ".jpeg", ".webp"}:
            raise ValueError(f"Missing original still at {start}: {image}")
        if end-start < 2:
            raise ValueError("Scene duration must be at least two frames")
        # Refuse properties whose meaning would be lost on image-to-video replacement.
        unsupported = set(clip)-{"id", "frames", "mediaRef", "mediaType", "keyframes", "transform",
                                "trimStartFrame", "trimEndFrame", "opacity", "crop", "blendMode",
                                "edgeRounding", "edgeSoftness", "fadeInFrames", "fadeOutFrames",
                                "fadeInInterpolation", "fadeOutInterpolation"}
        if unsupported:
            raise ValueError(f"Unsupported scene fields {sorted(unsupported)} at {start}; explicit adapter needed")
        mode = row.get("camera", config.get("camera", "auto"))
        keys, dx = camera_keys(clip, preset["camera_factor"], mode, i)
        sign = -1 if dx > .0025 else 1 if dx < -.0025 else (1 if i % 2 == 0 else -1)
        zoom = row.get("depth_zoom", config.get("depth_zoom"))
        if zoom is None or not isinstance(zoom, (float, int)) or not math.isfinite(zoom) or zoom <= 0:
            raise ValueError("Set depth_zoom per scene or explicitly in config; framing is not a universal preset")
        supplied_depth = row.get("depth")
        dep = path_from(supplied_depth, manifest_path.parent) if supplied_depth else None
        planned.append({"source": clip, "image": str(image), "image_hash": file_hash(image),
                        "depth_input": str(dep) if dep else None,
                        "depth_hash": file_hash(dep) if dep else None,
                        "keyframes": keys, "sign": sign, "depth_zoom": zoom,
                        "frames": end-start, "fps": state["fps"], "width": state["width"],
                        "height": state["height"], "preset": preset})
    if not planned:
        raise ValueError("No scene images found")
    grain = grain_settings(config)
    if grain:
        for scene in planned:
            scene["grain"] = grain
            finish_plan(scene)
    return planned


def worker_command(config):
    if config.get("render_python"):
        return [str(path_from(config["render_python"], ROOT)), str(HERE / "render.py")]
    if not shutil.which("uv"):
        raise RuntimeError("Install uv, or set render_python to a Python3.12 environment with depthflow==1.0.1")
    return ["uv", "run", "--locked", "--project", str(HERE), "--python", "3.12", "--", "python", str(HERE / "render.py")]


def execute(command, log):
    with log.open("a") as stream:
        subprocess.run(command, stdout=stream, stderr=subprocess.STDOUT, check=True)


def probe(path, scene, finished=False):
    result = subprocess.run(["ffprobe", "-v", "error", "-show_streams", "-of", "json", str(path)],
                            capture_output=True, text=True, check=True)
    streams = json.loads(result.stdout)["streams"]
    if len(streams) != 1 or streams[0]["codec_type"] != "video":
        raise ValueError("Expected exactly one video stream and no audio")
    v = streams[0]
    from fractions import Fraction
    if (v["width"], v["height"], int(v["nb_frames"])) != (scene["width"], scene["height"], scene["frames"]+2):
        raise ValueError(f"Wrong rendered size or frame count: {path}")
    if abs(float(Fraction(v["r_frame_rate"]))-scene["fps"]) > 1e-5:
        raise ValueError(f"Wrong rendered frame rate: {path}")
    if finished and (v.get("sample_aspect_ratio") != "1:1" or
                     float(v.get("start_time", -1)) != 0 or
                     any(v.get(k) != value for k, value in {
                         "color_range": "tv", "color_space": "bt709",
                         "color_transfer": "bt709", "color_primaries": "bt709"}.items())):
        raise ValueError(f"Wrong finished SAR/PTS/colour tags: {path}")


def prepare(scene, config, run_dir, depth_only=False, scratch_dir=None):
    depth_key = digest({"image": scene["image_hash"], "model": "DepthAnythingV2-small",
                        "depthflow": "1.0.1", "depth_input": scene["depth_hash"],
                        "worker": file_hash(HERE / "render.py")})
    depth_path = CACHE / "depth" / (depth_key + ".npy")
    depth_path.parent.mkdir(parents=True, exist_ok=True)
    # Lock shared cache entries, including runs on different timelines.
    with (CACHE / (depth_key + ".lock")).open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if not depth_path.exists():
            if scene["depth_input"]:
                shutil.copyfile(scene["depth_input"], depth_path)
            else:
                emit(stage="depth", image=scene["image"])
                execute(worker_command(config) + ["depth", scene["image"], str(depth_path)], run_dir / "renderer.log")
    if depth_only:
        return str(depth_path)
    job = {k: scene[k] for k in ("image", "frames", "fps", "width", "height", "sign", "depth_zoom")}
    job["preset"] = {k: scene["preset"][k] for k in ("offset", "height", "steady", "sticky")}
    job["depth"] = str(depth_path)
    signature = {**{k: v for k, v in job.items() if k != "image"},
                 "image": scene["image_hash"], "depth": file_hash(depth_path), "version": VERSION,
                 "worker": file_hash(HERE / "render.py")}
    video_key = digest(signature)
    video = CACHE / "video" / (video_key + ".mp4")
    video.parent.mkdir(parents=True, exist_ok=True)
    with (CACHE / (video_key + ".lock")).open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if video.exists():
            probe(video, scene)
            emit(stage="video-cache-hit", file=str(video))
            return str(video)
        scratch_dir = Path(scratch_dir) if scratch_dir else run_dir / 'scratch'
        scratch_dir.mkdir(parents=True, exist_ok=True)
        raw = scratch_dir / (video_key + ".raw.mp4")
        temporary = scratch_dir / (video_key + ".partial.mp4")
        opposite = CACHE / "video" / (digest({**signature, "sign": -scene["sign"]}) + ".mp4")
        reversing = opposite.exists()
        if reversing:
            probe(opposite, scene)
            emit(stage="reverse-cache", image=scene["image"], frames=scene["frames"])
        else:
            job["raw"] = str(raw)
            job_path = run_dir / (video_key + ".job.json")
            save(job_path, job)
            emit(stage="render", image=scene["image"], frames=scene["frames"], sign=scene["sign"])
            execute(worker_command(config) + ["render", str(job_path)], run_dir / "renderer.log")
        # Preserve N distinct motion frames; append two cloned tail frames for Palmier rounding.
        reverse_filter = "reverse," if reversing else ""
        execute(["ffmpeg", "-y", "-v", "error", "-i", str(opposite if reversing else raw), "-an", "-vf",
                 f"trim=end_frame={scene['frames']},{reverse_filter}setpts=PTS-STARTPTS,tpad=stop_mode=clone:stop_duration=1",
                 "-frames:v", str(scene["frames"]+2), "-c:v", "libx264", "-crf", "18",
                 "-preset", "fast", "-pix_fmt", "yuv420p", "-movflags", "+faststart", str(temporary)],
                run_dir / "renderer.log")
        probe(temporary, scene)
        temporary.replace(video)
        if raw.exists():
            raw.unlink()
    return str(video)


def prepare_finished(scene, config, run_dir, scratch_dir):
    """Separate cache layer: changing G08/camera never invalidates clean depth/parallax."""
    clean = prepare(scene, config, run_dir, scratch_dir=scratch_dir)
    if not scene.get("grain"):
        return clean
    scene["clean_video"] = clean
    runtime = (HERE / "uv.lock").read_bytes()
    signature = {"clean_sha256": file_hash(clean), "camera": scene["baked_camera"],
                 "grain": scene["grain"], "frames": scene["frames"], "fps": scene["fps"],
                 "width": scene["width"], "height": scene["height"],
                 "renderer": file_hash(HERE / "finish.py"),
                 "runtime": hashlib.sha256(runtime).hexdigest()}
    key = digest(signature)
    video = CACHE / "finished" / (key + ".mp4")
    video.parent.mkdir(parents=True, exist_ok=True)
    with (CACHE / (key + ".lock")).open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if video.exists():
            probe(video, scene, finished=True)
            receipt = json.loads(video.with_suffix(".json").read_text())
            if receipt.get("signature") != signature or receipt.get("sha256") != file_hash(video):
                raise ValueError(f"Finished cache identity changed; preserve and reconcile: {video}")
            emit(stage="finished-cache-hit", file=str(video))
            return str(video)
        scratch_dir = Path(scratch_dir)
        scratch_dir.mkdir(parents=True, exist_ok=True)
        partial = scratch_dir / (key + ".finished.partial.mp4")
        job = {k: scene[k] for k in ("width", "height", "frames", "fps", "grain")}
        job.update(input=clean, output=str(partial), camera=scene["baked_camera"],
                   seed=(int(scene["image_hash"][:16], 16) ^ scene["grain"]["seed"]),
                   receipt=str(run_dir / (key + ".finish-receipt.json")),
                   log=str(run_dir / "finish.log"))
        job_path = run_dir / (key + ".finish-job.json")
        save(job_path, job)
        command = worker_command(config)
        command[-1] = str(HERE / "finish.py")
        emit(stage="camera-grain", preset=scene["grain"]["id"], image=scene["image"])
        execute(command + [str(job_path)], run_dir / "finish.log")
        probe(partial, scene, finished=True)
        partial.replace(video)
        save(video.with_suffix(".json"), {"signature": signature, "sha256": file_hash(video),
                                         "receipt": job["receipt"]})
    return str(video)


def verify(source, result, scenes, scene_name):
    if [t.get("name", t.get("label")) for t in source["tracks"]] != [t.get("name", t.get("label")) for t in result["tracks"]]:
        raise ValueError("Track order changed")
    a, b = track(source, scene_name), track(result, scene_name)
    if not equal(canonical({k: v for k, v in a.items() if k != "clips"}),
                 canonical({k: v for k, v in b.items() if k != "clips"})):
        raise ValueError("Scene track settings changed")
    if len(a["clips"]) != len(b["clips"]):
        raise ValueError("Scene count changed")
    replacement = {tuple(s["source"]["frames"]): s for s in scenes}
    for original, actual in zip(a["clips"], b["clips"]):
        if original["frames"] != actual["frames"]:
            raise ValueError("Scene timing changed")
        scene = replacement.get(tuple(original["frames"]))
        if scene is None:
            if not equal(canonical(original), canonical(actual)):
                raise ValueError("Unselected scene changed")
            continue
        # Palmier omits mediaType for its default video type.
        if actual["mediaRef"] != scene["mediaRef"] or actual.get("mediaType", "video") != "video":
            raise ValueError("Wrong motion media on timeline")
        if not equal(actual.get("keyframes", {}), scene.get("target_keyframes", scene["keyframes"])):
            raise ValueError("Camera keyframes differ")
        for k, v in original.items():
            if k not in {"id", "mediaRef", "mediaType", "keyframes", "trimStartFrame", "trimEndFrame"}:
                if k == "transform" and scene.get("target_transform"):
                    continue  # Compare semantic defaults below; Palmier can omit identity fields.
                if k == "crop" and not any(v.values()) and not any((actual.get(k) or {}).values()):
                    continue  # Palmier may omit an all-zero crop after replacement.
                expected = v
                if not equal(expected, actual.get(k)):
                    raise ValueError(f"Scene property {k} changed")
        if scene.get("target_transform") and not equal(
                {**IDENTITY_TRANSFORM, **(actual.get("transform") or {})}, IDENTITY_TRANSFORM):
            raise ValueError("Baked camera must have identity transform")
        if actual.get("trimStartFrame", 0) != 0 or actual.get("trimEndFrame", 0) != 2:
            raise ValueError("Motion video trim changed")
    left = copy.deepcopy(source)
    right = copy.deepcopy(result)
    left["tracks"] = [t for t in left["tracks"] if t.get("name", t.get("label")) != scene_name]
    right["tracks"] = [t for t in right["tracks"] if t.get("name", t.get("label")) != scene_name]
    if not equal({k: v for k, v in canonical(left).items() if k != "name"},
                 {k: v for k, v in canonical(right).items() if k != "name"}):
        raise ValueError("Non-scene tracks or timeline settings changed")


def apply(palmier, config, source, scenes, run_dir, run):
    args = {"projectId": config["project_id"], "timelineId": config["timeline_id"]}
    if fingerprint(palmier.call("get_timeline", args)) != fingerprint(source):
        raise RuntimeError("Source timeline changed during rendering; rerun against its current timing")
    run["status"] = "applying"
    save(run_dir / "run.json", run)
    if run.get("target_timeline_id"):
        # Resume only an already-created clone whose content still matches the source.
        target = {**args, "timelineId": run["target_timeline_id"]}
        baseline = palmier.call("get_timeline", target)
    else:
        palmier.call("manage_snapshots", {**args, "action": "save", "name": "Before batch image motion"}, True)
        clone = palmier.call("create_timeline", {"projectId": args["projectId"], "from": args["timelineId"],
                                               "name": config.get("name", source["name"] + " — image motion")}, True)
        run["target_timeline_id"] = clone["timelineId"]
        save(run_dir / "run.json", run)
        target = {**args, "timelineId": clone["timelineId"]}
        baseline = palmier.call("get_timeline", target)
    if fingerprint(baseline) != fingerprint(source):
        raise RuntimeError("Clone does not match baseline")
    if not (run_dir / "target_before.json").exists():
        save(run_dir / "target_before.json", baseline)
    for scene in scenes:
        imported = palmier.call("import_media", {"projectId": args["projectId"],
                        "source": {"path": scene["video"]}, "folder": "ImageMotion"}, True)
        if not imported.get("mediaRef"):
            raise RuntimeError("Import did not return ready mediaRef")
        scene["mediaRef"] = imported["mediaRef"]
    run["scenes"] = scenes
    save(run_dir / "run.json", run)
    current_track = track(baseline, config.get("scene_track", "Scenes"))
    entries = [{"mediaRef": s["mediaRef"], "startFrame": s["source"]["frames"][0],
                "endFrame": s["source"]["frames"][1], "trackIndex": current_track["index"],
                "includeAudio": False} for s in scenes]
    # add_clips overwrite is frame-exact and retains the track (unlike removing its last clip).
    palmier.call("add_clips", {**target, "entries": entries}, True)
    after = palmier.call("get_timeline", target)
    scene_name = current_track.get("name", current_track.get("label"))
    actuals = {tuple(c["frames"]): c for c in track(after, scene_name)["clips"]}
    for scene in scenes:
        clip = actuals[tuple(scene["source"]["frames"])]
        props = {k: v for k, v in scene["source"].items() if k in {
            "transform", "crop", "opacity", "blendMode", "edgeRounding", "edgeSoftness",
            "fadeInFrames", "fadeOutFrames", "fadeInInterpolation", "fadeOutInterpolation"}}
        if scene.get("target_transform"):
            props["transform"] = scene["target_transform"]
        palmier.call("set_clip_properties", {**target, "clipIds": [clip["id"]],
                                            **props, "trimStartFrame": 0, "trimEndFrame": 2,
                                            "durationFrames": scene["frames"]}, True)
        for prop, keys in scene.get("target_keyframes", scene["keyframes"]).items():
            palmier.call("set_keyframes", {**target, "clipId": clip["id"], "property": prop, "keyframes": keys}, True)
    final = palmier.call("get_timeline", target)
    verify(baseline, final, scenes, scene_name)
    if fingerprint(palmier.call("get_timeline", args)) != fingerprint(source):
        raise RuntimeError("Source changed while applying; result needs reconciliation")
    save(run_dir / "target_final.json", final)
    snapshot = palmier.call("manage_snapshots", {**target, "action": "save", "name": "Batch image motion verified"}, True)
    run.update(status="complete", result_fingerprint=fingerprint(final), scenes=scenes, snapshot=snapshot,
               qa={"timeline_structure": "PASS", "full_playback": "UNVERIFIED"})
    save(run_dir / "run.json", run)
    emit(status="complete", timeline_id=target["timelineId"], scenes=len(scenes), run=str(run_dir / "run.json"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["plan", "prepare-depth", "apply"])
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--limit", type=int, help="Only first N scenes, for an isolated smoke test")
    opts = parser.parse_args()
    if opts.limit is not None and opts.limit < 1:
        parser.error("--limit must be positive")
    config_path = opts.config.resolve()
    config = json.loads(config_path.read_text())
    if opts.command == "apply" and config.get("motion_engine") != "legacy-depthflow-explicit":
        raise ValueError("Legacy DepthFlow does not implement the accepted opposed layered motion. "
                         "Use layered_render.py with prepared layers; only set motion_engine to "
                         "legacy-depthflow-explicit for an explicitly authorized legacy run.")
    episode = path_from(config["episode_dir"], config_path.parent)
    if episode.name == "001_radio_game" and opts.command == "apply":
        raise ValueError("Radio001 requires its canonical-timeline coordination procedure; generic cloning is disabled")
    if not episode.is_dir():
        raise ValueError("episode_dir does not exist")
    if opts.command == "prepare-depth":
        manifest_path = path_from(config["source_manifest"], config_path.parent)
        manifest = json.loads(manifest_path.read_text())
        rows = manifest if isinstance(manifest, list) else manifest["scenes"]
        root_runs = episode / "Edit" / "ImageMotion"
        root_runs.mkdir(parents=True, exist_ok=True)
        CACHE.mkdir(parents=True, exist_ok=True)
        for i, row in enumerate(rows[:opts.limit] if opts.limit else rows, 1):
            image = path_from(row.get("framed_path", row.get("image", row.get("path", ""))), manifest_path.parent)
            dep = path_from(row["depth"], manifest_path.parent) if row.get("depth") else None
            scene = {"image": str(image), "image_hash": file_hash(image),
                     "depth_input": str(dep) if dep else None, "depth_hash": file_hash(dep) if dep else None}
            prepare(scene, config, root_runs, depth_only=True)
            emit(stage="depth-ready", scene=i, image=str(image))
        return
    for command in ("ffmpeg", "ffprobe"):
        if not shutil.which(command):
            raise RuntimeError(f"Missing {command}")
    root_runs = episode / "Edit" / "ImageMotion"
    root_runs.mkdir(parents=True, exist_ok=True)
    with (root_runs / (digest([config["project_id"], config["timeline_id"]]) + ".lock")).open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        palmier = Palmier(root_runs)
        state = palmier.call("get_timeline", {"projectId": config["project_id"], "timelineId": config["timeline_id"]})
        media = palmier.call("get_media", {"projectId": config["project_id"]})
        scenes = make_plan(config, state, config_path.parent, opts.limit)
        assets = {a["id"]: a for a in media["assets"]}
        # Caption-group-only tracks omit the per-clip ``clips`` rows unless
        # get_timeline is called with captionDetail=true. They have no media
        # references that belong in this asset lookup.
        used_refs = {c["mediaRef"] for t in state["tracks"] for c in t.get("clips", [])
                     if c.get("mediaRef")}
        missing = sorted(used_refs - assets.keys())
        if missing:
            # Unfiltered inventory omits the Assets area; explicit ids includes it.
            extra = palmier.call("get_media", {"projectId": config["project_id"], "ids": missing})
            assets.update({a["id"]: a for a in extra["assets"]})
            media["assets"] = list(assets.values())
        for scene in scenes:
            asset = assets.get(scene["source"]["mediaRef"])
            if not asset or asset.get("type") != "image" or asset.get("generationStatus"):
                raise ValueError("A selected scene does not reference a ready image in this project library")
        # IDs and absolute source paths belong to the episode config, never the reusable code.
        identity = digest({"config": config, "source": fingerprint(state), "scenes": scenes,
                           "version": VERSION,
                           "finish_worker": file_hash(HERE / "finish.py") if any(s.get("grain") for s in scenes) else None,
                           "finish_runtime": file_hash(HERE / "uv.lock") if any(s.get("grain") for s in scenes) else None,
                           "worker": file_hash(HERE / "render.py")})
        resumable = []
        for candidate in root_runs.glob("*/run.json"):
            try:
                prior = json.loads(candidate.read_text())
                prior_source = json.loads((candidate.parent / "source.json").read_text())
                prior_plan = json.loads((candidate.parent / "plan.json").read_text())
            except (OSError, ValueError):
                continue
            if (prior.get("status") == "applying" and prior.get("target_timeline_id")
                    and not (candidate.parent / "pending.json").exists()
                    and fingerprint(prior_source) == fingerprint(state)
                    and canonical(prior_plan) == canonical(scenes)):
                resumable.append((candidate.parent, prior))
        if len(resumable) > 1:
            raise RuntimeError("Multiple incomplete motion runs match this source; reconcile them manually")
        run_dir, resumed_run = resumable[0] if resumable else (root_runs / identity[:20], None)
        run_dir.mkdir(exist_ok=True)
        palmier.run_dir = run_dir
        save(run_dir / "source.json", state)
        save(run_dir / "media.json", media)
        save(run_dir / "plan.json", scenes)
        save(run_dir / "tool_schemas.json", palmier.schemas)
        emit(stage="plan", scenes=len(scenes), preset=config.get("preset", "gentle-aligned"), run=str(run_dir))
        if opts.command == "plan":
            return
        run_path = run_dir / "run.json"
        run = resumed_run or (json.loads(run_path.read_text()) if run_path.exists() else
                              {"status": "rendering", "source_fingerprint": fingerprint(state)})
        if (run_dir / "pending.json").exists() or (run["status"] == "applying" and not run.get("target_timeline_id")):
            raise RuntimeError(f"Incomplete Palmier operation; reconcile {run_path} and receipts before retry. Target: {run.get('target_timeline_id')}")
        if run["status"] == "complete":
            actual = palmier.call("get_timeline", {"projectId": config["project_id"], "timelineId": run["target_timeline_id"]})
            if fingerprint(actual) != run["result_fingerprint"]:
                raise RuntimeError("Completed target was edited; preserve edits and choose a new run config")
            emit(status="unchanged", timeline_id=run["target_timeline_id"], run=str(run_path))
            return
        CACHE.mkdir(parents=True, exist_ok=True)
        save(run_path, run)
        for i, scene in enumerate(scenes, 1):
            scene["video"] = prepare_finished(
                scene, config, run_dir,
                scratch_dir=episode / 'Work' / ('image-motion-' + run_dir.name) / 'scratch')
            emit(stage="prepared", scene=i, total=len(scenes))
        if opts.command == "prepare-depth":
            emit(status="depth-ready", scenes=len(scenes))
            return
        apply(palmier, config, state, scenes, run_dir, run)


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        emit(status="failed", error=str(error))
        raise SystemExit(1)
